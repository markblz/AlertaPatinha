"""HTTP contract for relatos and the map. Locations go out as GeoJSON geometries:
MapLibre GL JS (web) and MapLibre Native (a future app) both consume them as-is."""

import uuid
from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field

from src.geo.public import AnimalFlag, DisplayMode, LocationView, RelatoKind
from src.observations.public import LocSource, PublicSeen, Species, TimePrecision

_DECIMALS = 6  # ~0.1 m: finer digits carry no information, only bytes


class LocationIn(BaseModel):
    # Brazil's bounding box. Platform scope, and a cheap junk filter.
    lat: float = Field(ge=-34.0, le=5.5)
    lng: float = Field(ge=-74.1, le=-28.6)
    accuracy_m: int | None = Field(default=None, ge=0, le=50_000)
    source: LocSource


CoatColor = Literal["black", "white", "caramel", "brown", "gray", "tabby", "tricolor", "spotted"]


class AttributesIn(BaseModel):
    """Structured only. No free text yet: public notes would carry phone
    numbers (Pix scams) and names before moderation exists (M4)."""

    model_config = ConfigDict(extra="forbid")

    size: Literal["small", "medium", "large"] | None = None
    coat_colors: list[CoatColor] = Field(default_factory=list, max_length=3)
    collar: bool | None = None
    injured: bool | None = None


class CreateRelatoIn(BaseModel):
    client_id: uuid.UUID  # generated by the client outbox; retries reuse it
    kind: RelatoKind
    species: Species
    animal_count: int = Field(default=1, ge=1, le=50)
    location: LocationIn
    seen_text: str | None = Field(default=None, max_length=120)  # None = agora
    flags: list[AnimalFlag] = Field(default_factory=list, max_length=3)
    attributes: AttributesIn = Field(default_factory=AttributesIn)


class RelatoCreated(BaseModel):
    id: uuid.UUID
    share_path: str


# GeoJSON defines a position as number[] (not a tuple); typed clients and
# MapLibre (web and native) all expect that shape.
Position = Annotated[list[float], Field(min_length=2, max_length=2)]  # [lng, lat]


class PointGeometry(BaseModel):
    type: Literal["Point"] = "Point"
    coordinates: Position


class PolygonGeometry(BaseModel):
    type: Literal["Polygon"] = "Polygon"
    coordinates: list[list[Position]]


Geometry = PointGeometry | PolygonGeometry


class LocationOut(BaseModel):
    mode: DisplayMode
    geometry: Geometry | None
    accuracy_m: int | None = None
    cell: str | None = None

    @classmethod
    def of(cls, view: LocationView) -> "LocationOut":
        return cls(
            mode=view.mode,
            geometry=geometry_of(view),
            accuracy_m=view.accuracy_m if view.point is not None else None,
            cell=view.cell,
        )


def geometry_of(view: LocationView) -> Geometry | None:
    if view.point is not None:
        return PointGeometry(
            coordinates=[round(view.point.lng, _DECIMALS), round(view.point.lat, _DECIMALS)]
        )
    if view.boundary:
        ring = [[round(p.lng, _DECIMALS), round(p.lat, _DECIMALS)] for p in view.boundary]
        return PolygonGeometry(coordinates=[[*ring, ring[0]]])
    return None


class SeenOut(BaseModel):
    start: datetime
    end: datetime
    precision: TimePrecision

    @classmethod
    def of(cls, seen: PublicSeen) -> "SeenOut":
        return cls(start=seen.start, end=seen.end, precision=seen.precision)


class RelatoOut(BaseModel):
    id: uuid.UUID
    kind: RelatoKind
    species: Species
    animal_count: int
    location: LocationOut
    seen: SeenOut
    attributes: dict[str, object]
    is_mine: bool


class MapFeatureProps(BaseModel):
    """Flat on purpose: MapLibre style expressions read top-level properties."""

    kind: RelatoKind
    species: Species
    animal_count: int
    display_mode: DisplayMode
    seen_start: datetime
    seen_end: datetime
    seen_precision: TimePrecision


class MapFeatureOut(BaseModel):
    type: Literal["Feature"] = "Feature"
    id: uuid.UUID
    geometry: Geometry
    properties: MapFeatureProps


class MapOut(BaseModel):
    type: Literal["FeatureCollection"] = "FeatureCollection"
    features: list[MapFeatureOut]
    truncated: bool = False  # more than the cap: zoom in for the rest
    zoom_in: bool = False  # bbox wider than the cap: nothing returned
